class AutoDetectionTests(unittest.TestCase):

    def test_detect_vmd_install_returns_none_when_nothing_present(self):
        """With no VMD installed and no env vars, detection returns None
        rather than raising. The CI machine running these tests has no
        VMD, so this is the realistic path."""
        old = os.environ.pop("VMD_INSTALL_DIR", None)
        old2 = os.environ.pop("VMDDIR", None)
        try:
            # Detection might find an OS-provided VMD on dev machines —
            # if that happens, just verify the call returns either None
            # or a real existing directory.
            result = _detect_vmd_install()
            if result is not None:
                self.assertTrue(result.is_dir())
        finally:
            if old is not None:
                os.environ["VMD_INSTALL_DIR"] = old
            if old2 is not None:
                os.environ["VMDDIR"] = old2

    def test_detect_vmd_install_honors_env_var(self):
        """A user-set VMD_INSTALL_DIR wins over heuristic search."""
        with tempfile.TemporaryDirectory() as tmp:
            os.environ["VMD_INSTALL_DIR"] = tmp
            try:
                result = _detect_vmd_install()
                self.assertEqual(result, Path(tmp))
            finally:
                os.environ.pop("VMD_INSTALL_DIR", None)

    def test_detect_user_guide_html_finds_html_files(self):
        """Given an install dir that contains doc/ug/<x.html>, the
        helper should return the doc/ug path."""
        with tempfile.TemporaryDirectory() as tmp:
            install = Path(tmp)
            ug_dir = install / "doc" / "ug"
            ug_dir.mkdir(parents=True)
            (ug_dir / "chap1.html").write_text("<h1>X</h1>", encoding="utf-8")
            self.assertEqual(_detect_user_guide_html(install), ug_dir)

    def test_detect_user_guide_html_returns_none_when_empty(self):
        with tempfile.TemporaryDirectory() as tmp:
            install = Path(tmp)
            (install / "doc").mkdir()
            self.assertIsNone(_detect_user_guide_html(install))

    def test_detect_vmd_binary_returns_none_for_empty_install(self):
        """Without a vmd in PATH and an empty install dir, returns None."""
        with tempfile.TemporaryDirectory() as tmp:
            install = Path(tmp)
            result = _detect_vmd_binary(install)
            # We can't guarantee `which vmd` returns nothing in every
            # dev environment, so this test is permissive: either None
            # (clean env) or a real existing executable (dev with VMD).
            if result is not None:
                self.assertTrue(result.is_file())
                self.assertTrue(os.access(result, os.X_OK))


