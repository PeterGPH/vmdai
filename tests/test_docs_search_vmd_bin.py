class ExtensionClassificationTests(unittest.TestCase):

    def test_md_classified_as_markdown(self):
        self.assertEqual(_classify_extension(Path("/x/foo.md")), "markdown")

    def test_html_and_htm_classified(self):
        self.assertEqual(_classify_extension(Path("/x/a.html")), "html")
        self.assertEqual(_classify_extension(Path("/x/a.htm")), "html")

    def test_txt_classified_as_plaintext(self):
        self.assertEqual(_classify_extension(Path("/x/r.txt")), "plaintext_ref")

    def test_unknown_extension_returns_none(self):
        self.assertIsNone(_classify_extension(Path("/x/r.png")))
        self.assertIsNone(_classify_extension(Path("/x/r")))


