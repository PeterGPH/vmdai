"""
Tests for the --vmd-bin path: indexer runs dump_help.tcl in headless
VMD and ingests the resulting plaintext into the vmd_ref scope.

We never have a real VMD on test machines, so the test installs a
small shell-script "stub" that mimics:

    vmd -dispdev text -e <script>

The stub honors $VMD_AI_HELP_OUT (the path the indexer tells dump_help
to write to) and writes a canned help corpus. The point of these tests
is to verify the indexer's subprocess plumbing — that it sets the env
var, locates the script, captures the output, and pipes it into the
plaintext chunker.

Auto-detection paths and missing-binary paths are covered separately.
"""
from __future__ import annotations

import json
import os
import stat
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_DIR = ROOT / "runtime"
if str(RUNTIME_DIR) not in sys.path:
    sys.path.insert(0, str(RUNTIME_DIR))

from vmd_ai_runtime.docs_search import DocsSearch  # noqa: E402
from vmd_ai_runtime.scripts.build_docs_index import (  # noqa: E402
    _classify_extension,
    _detect_user_guide_html,
    _detect_vmd_binary,
    _detect_vmd_install,
    cli as indexer_cli,
)


# ----------------------------------------------------------------------
# Stub-binary builder
# ----------------------------------------------------------------------

STUB_HELP_TEXT = """# VMD AI help dump v1
# generated by stub vmd

=== mol ===
Usage: mol <subcommand> [args...]
Subcommands include: load, new, delete, representation, color, addrep,
delrep, selection, material.
Use `mol load pdb 1ubq.pdb` to load a structure by PDB ID file.

=== atomselect ===
Create a selection object: atomselect <molid> "<selection_string>".
Returns a Tcl proc handle. Always call $sel delete when done.

=== render ===
Render the current viewport to disk. Two backends:
- render snapshot <file>           # OpenGL framebuffer, fast TGA
- render TachyonInternal <file>    # ray-traced, slower

=== measure ===
Geometric measurements over selections:
- measure rmsd <selA> <selB>
- measure hbonds <cutoff> <angle> <selA> [<selB>]
- measure contacts <cutoff> <selA> <selB>     # cross-molecule friendly

# documented=4 missing=0
"""


def _make_stub_vmd(work_dir: Path, *, exit_code: int = 0,
                  emit_output: bool = True) -> Path:
    """Write an executable shell script that pretends to be `vmd`.

    The real call is `vmd -dispdev text -e <script.tcl>`. The stub
    ignores its args, reads $VMD_AI_HELP_OUT, and writes STUB_HELP_TEXT
    there (or skips writing if `emit_output=False`, to test the
    no-output failure mode).
    """
    stub_path = work_dir / "vmd_stub.sh"
    out_branch = (
        f'cat > "$VMD_AI_HELP_OUT" <<\'EOF\'\n{STUB_HELP_TEXT}EOF\n'
        if emit_output else ""
    )
    stub_path.write_text(
        "#!/usr/bin/env bash\n"
        "# stub vmd binary for tests\n"
        f"{out_branch}"
        f"exit {exit_code}\n"
    )
    stub_path.chmod(stub_path.stat().st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
    return stub_path


# ----------------------------------------------------------------------
# Subprocess plumbing
# ----------------------------------------------------------------------

class VmdBinIndexerTests(unittest.TestCase):

    def test_vmd_bin_help_dump_is_indexed(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp_p = Path(tmp)
            stub = _make_stub_vmd(tmp_p)
            out_dir = tmp_p / "idx"

            rc = indexer_cli([
                "--rebuild",
                "--out", str(out_dir),
                "--skills", "/dev/null",
                "--vmd-bin", str(stub),
            ])
            self.assertEqual(rc, 0)

            ds = DocsSearch(index_dir=str(out_dir))
            self.assertTrue(ds.is_available)

            # Searching for a topic only present in the stub help text
            # should retrieve it. If this fails the indexer didn't
            # actually invoke the stub or didn't pipe its output in.
            res = ds.search("how do I render TachyonInternal", k=3)
            self.assertTrue(res["ok"])
            joined = " ".join(r["text"] for r in res["results"])
            self.assertIn("TachyonInternal", joined)

    def test_vmd_bin_failure_does_not_break_index(self):
        """If the vmd binary fails, the indexer falls back to the other
        sources without crashing. We pass --user-guide so the index is
        non-empty, and verify the overall build still succeeds."""
        with tempfile.TemporaryDirectory() as tmp:
            tmp_p = Path(tmp)
            failing = _make_stub_vmd(tmp_p, exit_code=1, emit_output=False)
            out_dir = tmp_p / "idx"

            rc = indexer_cli([
                "--rebuild",
                "--out", str(out_dir),
                "--user-guide",
                str(ROOT / "tests" / "fixtures" / "docs" / "user_guide_html"),
                "--skills", "/dev/null",
                "--vmd-bin", str(failing),
            ])
            # The fallback path should still produce a usable index.
            self.assertEqual(rc, 0)
            ds = DocsSearch(index_dir=str(out_dir))
            self.assertTrue(ds.is_available)

    def test_vmd_bin_no_output_file_handled(self):
        """If the binary exits 0 but writes nothing, we shouldn't claim
        the help dump is in the index."""
        with tempfile.TemporaryDirectory() as tmp:
            tmp_p = Path(tmp)
            silent = _make_stub_vmd(tmp_p, exit_code=0, emit_output=False)
            out_dir = tmp_p / "idx"

            rc = indexer_cli([
                "--rebuild",
                "--out", str(out_dir),
                "--user-guide",
                str(ROOT / "tests" / "fixtures" / "docs" / "user_guide_html"),
                "--skills", "/dev/null",
                "--vmd-bin", str(silent),
            ])
            self.assertEqual(rc, 0)
            # Manifest's vmd_ref count should be 0 — only user_guide
            # made it in.
            manifest = json.loads(
                (out_dir / "manifest.json").read_text()
            )
            self.assertNotIn("vmd_ref", manifest["scope_counts"])
            self.assertIn("user_guide", manifest["scope_counts"])

    def test_vmd_bin_missing_executable(self):
        """Pointing at a non-existent binary should not raise."""
        with tempfile.TemporaryDirectory() as tmp:
            tmp_p = Path(tmp)
            bogus = tmp_p / "definitely_not_a_binary"
            out_dir = tmp_p / "idx"

            rc = indexer_cli([
                "--rebuild",
                "--out", str(out_dir),
                "--user-guide",
                str(ROOT / "tests" / "fixtures" / "docs" / "user_guide_html"),
                "--skills", "/dev/null",
                "--vmd-bin", str(bogus),
            ])
            # User-guide source still produces an index.
            self.assertEqual(rc, 0)


